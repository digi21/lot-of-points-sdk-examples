def texts_for(language_code):
    """Returns the dictionary key -> text of the language with the given ISO 639-1 code, or the English one for any other code."""
    language_index = LANGUAGE_CODES.index(language_code) if language_code in LANGUAGE_CODES else LANGUAGE_CODES.index("en")
    return {key: texts[language_index] for key, texts in CAMERA_PATH_TRANSLATIONS_BY_TEXT_ID.items()}
